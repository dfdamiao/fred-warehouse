def _is_excluded(series_id: str) -> bool:
    if series_id in _DISCONTINUED_2023 or series_id in _DISCONTINUED_INDIVIDUAL:
        return True
    for p in _EXCLUDE_PREFIXES:
        if series_id.startswith(p):
            return True
    for c in _EXCLUDE_CONTAINS:
        if c in series_id:
            return True
    return False


